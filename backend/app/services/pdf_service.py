import re
from datetime import datetime
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (
    HRFlowable,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

ACCENT = colors.HexColor("#1F6FEB")
INK = colors.HexColor("#1B1F24")
MUTED = colors.HexColor("#6B7280")
RULE = colors.HexColor("#D5DBE5")
ZEBRA = colors.HexColor("#F3F6FB")

PAGE_W, _ = A4
CONTENT_W = PAGE_W - 4 * cm

_REPLACEMENTS = {"₹": "INR ", "→": "->", "←": "<-", "✓": "", "•": "-", "\u00a0": " "}


def _clean(text: str) -> str:
    """Helvetica only covers Latin-1/WinAnsi; drop emoji and other unsupported glyphs."""
    for k, v in _REPLACEMENTS.items():
        text = text.replace(k, v)
    return text.encode("cp1252", errors="ignore").decode("cp1252")


def _inline(text: str) -> str:
    text = escape(_clean(text))
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"(?<![*\w])\*(?!\s)(.+?)(?<!\s)\*(?![*\w])", r"<i>\1</i>", text)
    text = re.sub(r"`(.+?)`", r"<font face='Courier'>\1</font>", text)
    return text


def _styles() -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()["Normal"]
    return {
        "title": ParagraphStyle("title", parent=base, fontName="Helvetica-Bold",
                                fontSize=22, leading=26, textColor=ACCENT, spaceAfter=2),
        "subtitle": ParagraphStyle("subtitle", parent=base, fontSize=9,
                                   textColor=MUTED, spaceAfter=10),
        "section": ParagraphStyle("section", parent=base, fontName="Helvetica-Bold",
                                  fontSize=15, leading=19, textColor=ACCENT,
                                  spaceBefore=16, spaceAfter=2),
        "sub": ParagraphStyle("sub", parent=base, fontName="Helvetica-Bold",
                              fontSize=11.5, leading=15, textColor=INK,
                              spaceBefore=10, spaceAfter=3),
        "label": ParagraphStyle("label", parent=base, fontName="Helvetica-Bold",
                                fontSize=10, leading=14, textColor=INK,
                                spaceBefore=6, spaceAfter=2),
        "body": ParagraphStyle("body", parent=base, fontSize=10, leading=14.5,
                               textColor=INK, spaceAfter=4),
        "bullet": ParagraphStyle("bullet", parent=base, fontSize=10, leading=14.5,
                                 textColor=INK, leftIndent=16, bulletIndent=4, spaceAfter=2),
        "th": ParagraphStyle("th", parent=base, fontName="Helvetica-Bold",
                             fontSize=9, leading=12, textColor=colors.white),
        "td": ParagraphStyle("td", parent=base, fontSize=9, leading=12, textColor=INK),
    }


def _table(rows: list[list[str]], st: dict) -> Table:
    ncols = max(len(r) for r in rows)
    data = []
    for i, row in enumerate(rows):
        row = row + [""] * (ncols - len(row))
        style = st["th"] if i == 0 else st["td"]
        data.append([Paragraph(_inline(c), style) for c in row])
    t = Table(data, colWidths=[CONTENT_W / ncols] * ncols, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), ACCENT),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, ZEBRA]),
        ("GRID", (0, 0), (-1, -1), 0.4, RULE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    return t


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(MUTED)
    canvas.drawString(2 * cm, 1.1 * cm, "Travel XYZ")
    canvas.drawRightString(PAGE_W - 2 * cm, 1.1 * cm, f"Page {doc.page}")
    canvas.restoreState()


def markdown_to_pdf(title: str, markdown_text: str) -> bytes:
    st = _styles()
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        leftMargin=2 * cm, rightMargin=2 * cm, topMargin=2 * cm, bottomMargin=2 * cm,
        title=_clean(title),
    )

    story = [
        Paragraph(escape(_clean(title)), st["title"]),
        Paragraph(f"Generated by Travel XYZ on {datetime.now():%d %b %Y}", st["subtitle"]),
        HRFlowable(width="100%", thickness=1.2, color=ACCENT, spaceAfter=6),
    ]

    table_rows: list[list[str]] = []
    skipped_title = False

    def flush_table():
        nonlocal table_rows
        if table_rows:
            story.extend([_table(table_rows, st), Spacer(1, 8)])
            table_rows = []

    for raw in markdown_text.splitlines():
        line = raw.strip()

        # --- markdown tables ---
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if not all(re.fullmatch(r":?-{2,}:?", c) for c in cells if c):
                table_rows.append(cells)
            continue
        flush_table()

        if not line:
            story.append(Spacer(1, 4))
        elif re.fullmatch(r"[-*_]{3,}", line):
            story.append(HRFlowable(width="100%", thickness=0.5, color=RULE, spaceBefore=4, spaceAfter=4))
        elif line.startswith("# "):
            if not skipped_title:  # the PDF title already covers the first H1
                skipped_title = True
                continue
            story.extend([Paragraph(_inline(line[2:]), st["section"]),
                          HRFlowable(width="100%", thickness=0.5, color=RULE, spaceAfter=4)])
        elif line.startswith("## "):
            story.extend([Paragraph(_inline(line[3:]), st["section"]),
                          HRFlowable(width="100%", thickness=0.5, color=RULE, spaceAfter=4)])
        elif line.startswith("#"):
            story.append(Paragraph(_inline(line.lstrip("#").strip()), st["sub"]))
        elif line.startswith(("* ", "- ")):
            story.append(Paragraph(_inline(line[2:]), st["bullet"], bulletText="-"))
        elif re.match(r"\d+[.)]\s+", line):
            num, rest = re.split(r"[.)]\s+", line, maxsplit=1)
            story.append(Paragraph(_inline(rest), st["bullet"], bulletText=f"{num}."))
        elif line.endswith(":") and len(line) < 60:
            story.append(Paragraph(_inline(line), st["label"]))  # e.g. "Price Estimates:"
        else:
            story.append(Paragraph(_inline(line), st["body"]))

    flush_table()
    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()